#!/usr/bin/env python3
"""Emit lib/gallery.ts from content-inventory.json so the app has typed data."""
import json
import os

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
inv = json.load(open(os.path.join(BASE, "content-inventory.json"), encoding="utf-8"))

GROUPS = {
    "fashion": [
        ("lukacev-couture", "Lukacev Couture", "Couture editorial"),
        ("trinity-collection", "The Trinity Collection", "Collection story"),
        ("street-style-bags", "Street Style & Statement Bags", "Street style"),
        ("burgundy-looks", "Burgundy Looks", "Lookbook"),
        ("runway-collection", "Runway Edit", "Runway"),
        ("streetwear-sneakers", "Streetwear & Sneakers", "Streetwear"),
        ("paris-fashion-week", "Paris Fashion Week", "Editorial"),
        ("navy-burgundy", "Navy & Burgundy", "Lookbook"),
        ("tom-ford-editorial", "Tom Ford Editorial", "Creative direction"),
        ("halloween-romance", "Halloween Romance", "Seasonal"),
        ("city-coffee", "City & Coffee", "Lifestyle styling"),
        ("parisian-summer", "Parisian Summer", "Seasonal"),
        ("halloween-peek", "Halloween Preview", "Seasonal"),
        ("ootd-styling", "Everyday Styling", "OOTD"),
    ],
    "beauty": [("sultry-fragrance", "Sultry Extrait de Parfum", "Fragrance")],
    "lifestyle": [("green-door-candle", "Green Door Candle Co.", "Home fragrance")],
}

images = inv["images"]
by_slug = {}
for a in images:
    by_slug.setdefault(a["slug"], []).append(a)

works = []
for cat, entries in GROUPS.items():
    for slug, title, kind in entries:
        items = sorted(by_slug.get(slug, []), key=lambda x: x["index"])
        if not items:
            continue
        cover = items[0]
        works.append({
            "slug": slug,
            "title": title,
            "kind": kind,
            "category": cat,
            "postUrl": items[0].get("post_url", ""),
            "cover": cover["src"],
            "coverRatio": cover["ratio"],
            "images": [{"src": i["src"], "ratio": i["ratio"], "width": i["width"],
                        "height": i["height"]} for i in items],
        })

video_map = {v["id"]: v for v in inv["videos"]}
films = []
for vid, meta in video_map.items():
    films.append({
        "id": vid,
        "title": meta["title"],
        "category": meta["category"],
        "postUrl": meta["post_url"],
        "src": meta["file"],
    })

# order films deliberately
order = ["beauty-7705255935966547207", "beauty-7707596540352744712",
         "haircare-7709816611305262344", "fashion-7702357591774661895"]
films.sort(key=lambda f: order.index(f["id"]) if f["id"] in order else 99)

ts = ["// AUTO-GENERATED by scripts/gen_gallery.py — do not edit by hand",
      "export type WorkImage = { src: string; ratio: number; width: number; height: number };",
      "export type Work = { slug: string; title: string; kind: string; category: 'fashion' | 'beauty' | 'lifestyle'; postUrl: string; cover: string; coverRatio: number; images: WorkImage[] };",
      "export type Film = { id: string; title: string; category: string; postUrl: string; src: string };",
      "",
      "export const works: Work[] = " + json.dumps(works, indent=2) + ";",
      "",
      "export const films: Film[] = " + json.dumps(films, indent=2) + ";",
      "",
      "export const profile = {",
      "  name: 'Valentina Rose',",
      "  studio: 'Val Rose Studio',",
      "  handle: '@valrose.studio0',",
      "  tiktok: 'https://www.tiktok.com/@valrose.studio0',",
      "  email: 'valrose.model@gmail.com',",
      "  followers: '1.2K',",
      "  likes: '17.8K',",
      "};",
      ""]

os.makedirs(os.path.join(BASE, "lib"), exist_ok=True)
with open(os.path.join(BASE, "lib", "gallery.ts"), "w", encoding="utf-8") as f:
    f.write("\n".join(ts))

print("works:", len(works), "films:", len(films),
      "images total:", sum(len(w["images"]) for w in works))
